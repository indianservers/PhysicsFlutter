"""Compile the reviewed, lab-specific UX profiles into an offline Dart registry."""
from pathlib import Path
import json

root = Path(__file__).resolve().parents[1]
items = []
for line in (root / 'lib/content/lab_research_profiles.tsv').read_text(encoding='utf-8').splitlines():
    if not line.strip():
        continue
    fields = line.split('|')
    assert len(fields) == 10, fields[0]
    lab_id, focus, focus_title, contrast, compare_title, watch, watch_title, plot, plot_title, prompt = fields
    key, value = focus.split(':')
    plot_key, plot_reading = plot.split(':')
    comparison = None
    if contrast != '-':
        compare_key, a, b = contrast.split(':')
        comparison = {'key': compare_key, 'a': float(a), 'b': float(b)}
    items.append({'id': lab_id, 'focus': {'key': key, 'value': float(value)},
                  'focusTitle': focus_title, 'comparison': comparison, 'compareTitle': compare_title,
                  'watchKeys': watch.split(','), 'watchTitle': watch_title,
                  'plotKey': plot_key, 'plotReading': plot_reading, 'plotTitle': plot_title, 'prompt': prompt})
assert len(items) == 116 and len({item['id'] for item in items}) == 116
source = '''// Generated by tool/generate_lab_research_profiles.py from the reviewed TSV.
import 'dart:convert';

class LabResearchProfile {
  final String id, focusKey, focusTitle, compareTitle, watchTitle, plotKey, plotReading, plotTitle, prompt;
  final double focusValue;
  final String? compareKey;
  final double? compareA, compareB;
  final List<String> watchKeys;
  const LabResearchProfile(this.id, this.focusKey, this.focusValue, this.focusTitle,
      this.compareKey, this.compareA, this.compareB, this.compareTitle, this.watchKeys,
      this.watchTitle, this.plotKey, this.plotReading, this.plotTitle, this.prompt);
  List<String> get suggestions => [focusTitle, compareTitle, watchTitle, plotTitle, prompt];
  factory LabResearchProfile.fromJson(Map<String, dynamic> m) => LabResearchProfile(
      m['id'], m['focus']['key'], (m['focus']['value'] as num).toDouble(), m['focusTitle'],
      m['comparison']?['key'], (m['comparison']?['a'] as num?)?.toDouble(),
      (m['comparison']?['b'] as num?)?.toDouble(), m['compareTitle'],
      List<String>.from(m['watchKeys']), m['watchTitle'], m['plotKey'], m['plotReading'],
      m['plotTitle'], m['prompt']);
}

final labResearchProfiles = {
  for (final raw in jsonDecode(_profiles) as List)
    raw['id'] as String: LabResearchProfile.fromJson(Map<String, dynamic>.from(raw)),
};
const _profiles = r\'''REPLACE\''';
'''.replace('REPLACE', json.dumps(items, ensure_ascii=False, separators=(',', ':')))
(root / 'lib/content/lab_research_profiles.dart').write_text(source, encoding='utf-8')
print(f'Generated {len(items)} reviewed lab profiles / {len(items) * 5} specific enhancements.')
