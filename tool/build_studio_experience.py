"""Compile the reviewed offline studio tools and their implementation checklist."""
import json
from pathlib import Path
import csv

root = Path(__file__).resolve().parents[1]
definitions = json.loads((root / 'tool/studio_investigation_definitions.json').read_text(encoding='utf-8'))
assert len(definitions) == 170
assert len({v['id'] for v in definitions}) == 170
assert all(sum(v['studio'] == s for v in definitions) == 10 for s in range(17))
payload = json.dumps(definitions, ensure_ascii=False, separators=(',', ':'))
source = '''// Generated by tool/build_studio_experience.py from reviewed definitions.
import 'dart:convert';

class StudioInvestigation {
  final String id, labId, title, why, prompt;
  final int studio;
  final List<String> method, watch;
  final Map<String, double> a, b;
  final Map<String, String> overview;
  const StudioInvestigation(this.id, this.labId, this.title, this.why,
      this.prompt, this.studio, this.method, this.watch, this.a, this.b, this.overview);
  factory StudioInvestigation.fromJson(Map<String, dynamic> m) => StudioInvestigation(
    m['id'], m['labId'], m['title'], m['why'], m['prompt'], m['studio'],
    List<String>.from(m['method']), List<String>.from(m['watch']),
    (m['a'] as Map).map((k,v) => MapEntry(k as String, (v as num).toDouble())),
    (m['b'] as Map).map((k,v) => MapEntry(k as String, (v as num).toDouble())),
    Map<String,String>.from(m['overview'] ?? {}));
}
final studioInvestigations = List<StudioInvestigation>.unmodifiable(
  (jsonDecode(_definitions) as List).map((m) => StudioInvestigation.fromJson(m)));
StudioInvestigation? studioInvestigation(String? id) =>
  studioInvestigations.where((v) => v.id == id).firstOrNull;
const _definitions = r\'\'\'PAYLOAD\'\'\';
'''.replace('PAYLOAD', payload)
(root / 'lib/content/studio_investigations.dart').write_text(source, encoding='utf-8')
common = [
 ('Searchable controls', 'Find inputs by name, symbol or unit, see the result count and clear the filter.'),
 ('Precise bounded entry', 'Open the existing precision editor beside every current control, with its live range and units.'),
 ('Selectable fine steps', 'Choose 0.01%, 0.1% or 1% of the current control range; use named decrease/increase buttons without dragging.'),
 ('Previewed paired setups', 'Inspect actual A/B control values and units before applying a studio setup; unavailable mode controls block the whole change.'),
 ('Setup undo and redo', 'Undo and redo complete source configurations, including model options and time; recorded trials remain separate.'),
 ('Baseline change ledger', 'Review changes from the temporary opening reference, replace that reference explicitly, or restore it with Undo available.'),
 ('Focused live readings', 'Search calculated readings, pin useful quantities to the top and switch between the curated focus and all values.'),
 ('Visible capture readiness', 'Show current validity and the full source notice; block evidence capture until the apparatus/model is ready.'),
 ('Fair A/B interpretation', 'Capture two actual paused states; show changed conditions and compute a secant only for one changed input, matching mode/units and equal available model time.'),
 ('Deliberate evidence sharing', 'Copy only the selected setup inputs, calculated readings and explicit A/B evidence; source notes and histories are excluded.'),
]
catalog = (root / 'lib/content/catalog.dart').read_text(encoding='utf-8')
studios = json.loads(catalog.split("const _catalog = r'''",1)[1].split("'''",1)[0])
lines = ['# Shared and studio-specific UI/UX improvements', '',
 '**10 common improvements + 10 tailored tools in each of 17 studios = 180 review items.**', '',
 'The common workbench serves all 116 physical labs. The six Concept Overview tools have 10 focused discovery actions. '
 'Studio tools wrap the existing scientific models with previewed setups, focused readings, reversible controls and explicit evidence; they are not additional physics engines.', '',
 'Open **Lab options → Exploration workbench** in a physical lab, or **10 studio tools** from a studio page. '
 'Opening a studio tool only opens its lab and preview; applying a setup and capturing evidence are explicit actions. '
 'The earlier lab-specific Tune/Compare/Watch/Plot/Explain tools remain available.', '',
 '## Ten common improvements', '']
rows=[]
for n,(title,detail) in enumerate(common,1):
    lines.append(f'{n}. **{title}** — {detail}')
    rows.append(dict(id=f'common-{n:02}',studio='All 116 physical labs',lab_id='*',enhancement=title,behavior=detail))
for s in range(17):
    lines.extend(['',f"## {studios[s]['title']}",''])
    for n,v in enumerate((v for v in definitions if v['studio']==s),1):
        action = ('Apply the focused discovery action in its actual overview tool.' if s==0 else
                  'Preview and apply A/B setups through the actual source controls; inspect the curated live quantities and explicitly capture evidence.')
        lines.append(f"{n}. **{v['title']}** (`{v['labId']}`) — {v['why']} {action}")
        rows.append(dict(id=v['id'],studio=studios[s]['title'],lab_id=v['labId'],enhancement=v['title'],behavior=action))
(root / 'docs/STUDIO_COMMON_UX_SUGGESTIONS.md').write_text('\n'.join(lines)+'\n',encoding='utf-8')
with (root / 'docs/STUDIO_COMMON_UX_CHECKLIST.csv').open('w',newline='',encoding='utf-8-sig') as file:
    writer=csv.DictWriter(file,fieldnames=rows[0].keys());writer.writeheader();writer.writerows(rows)
print('Generated 170 studio tools and the 180-item implementation checklist.')
