import '../../core/physics/dynamics.dart';

class Parameter {
  final String key, label, unit;
  final double min, max, initial;
  const Parameter(
    this.key,
    this.label,
    this.unit,
    this.min,
    this.max,
    this.initial,
  );
}

class DynamicsLesson {
  final String apparatus,
      principle,
      procedure,
      limits,
      mistake,
      question,
      formula,
      symbols,
      example,
      metric,
      unit;
  final List<Parameter> controls;
  const DynamicsLesson(
    this.apparatus,
    this.principle,
    this.procedure,
    this.limits,
    this.mistake,
    this.question,
    this.formula,
    this.symbols,
    this.example,
    this.metric,
    this.unit,
    this.controls,
  );
  Map<String, double> get defaults => {
    for (final p in controls) p.key: p.initial,
  };
}

