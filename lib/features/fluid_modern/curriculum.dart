List<Parameter> fmControls(
  int kind,
  int mode,
) => fmLessons[kind].controls.where((p) {
  if (kind == 1 && mode == 0 && ['layerDensity', 'oilVolume'].contains(p.key)) {
    return false;
  }
  if (kind == 2 && mode == 0 && p.key == 'bottomDepth') return false;
  if (kind == 7 && p.key == (mode == 0 ? 'frequency' : 'wavelength')) {
    return false;
  }
  if (kind == 8 && p.key == (mode == 0 ? 'momentum' : 'voltage')) return false;
  return true;
}).toList();
