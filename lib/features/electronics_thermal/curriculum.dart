List<Parameter> etControls(int k, int m) => etLessons[k].controls.where((p) {
  if (k == 0 && p.key == 'doping') return m != 0;
  if (k == 4 && p.key == 'inputB') return m != 2;
  if (k == 5) {
    return [
      ['temperature'],
      ['lux'],
      ['distance', 'airTemperature'],
    ][m].contains(p.key);
  }
  if (k == 6 && m == 0) {
    return ['sampleT', 'probeT', 'probeTau'].contains(p.key);
  }
  if (k == 7) {
    return [
      ['conductivity', 'area', 'length', 'leftT', 'rightT', 'probe'],
      [
        'initialT',
        'ambientT',
        'h',
        'surface',
        'mass',
        'cp',
        'conductivity',
        'density',
      ],
      ['initialT', 'ambientT', 'emissivity', 'surface', 'mass', 'cp'],
    ][m].contains(p.key);
  }
  if (k == 8 || k == 9) {
    final process = k == 8 ? m : [1, 2, 0, 3][m];
    if (p.key == 'temperatureRatio') return process == 1;
    if (p.key == 'volumeRatio') return process != 1;
  }
  if (k == 10) {
    return [
      [
        'amount',
        'initialT',
        'initialVolume',
        'volumeRatio',
        'finalT',
        'duration',
      ],
      ['amount', 'initialT', 'initialVolume', 'volumeRatio', 'expanded'],
      ['body1T', 'body2T', 'capacity1', 'capacity2', 'conductance'],
    ][m].contains(p.key);
  }
  return true;
}).toList();
